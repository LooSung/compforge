#!/usr/bin/env bash
#
# compforge init — deliver Compforge's constitution and enforcement into a
# target project.
#
# Leaves two things behind that survive a clone:
#   1. An AGENTS.md pointer block — an agent that clones only the target repo
#      learns to read the pack before touching UI code. The Hard Rules are not
#      copied; the block records what this repo is pinned to.
#   2. The stack's enforcement template (ESLint import zones and/or
#      no-explicit-any, steiger for FSD) plus a GitHub Actions check, with
#      per-feature zones generated from the directories that actually exist.
#
# Then it runs a negative self-test: a deliberate violation must fail lint. A
# silent no-op (the .ts resolver trap) cannot survive an install. It also
# refuses a tsconfig that does not set compilerOptions.strict to true.
#
# What it never does: overwrite a file it did not generate, install npm
# dependencies, or touch package.json / tsconfig.json. Existing files get a
# printed merge snippet instead; an existing AGENTS.md keeps everything
# outside the markers. Missing tsc --noEmit is a printed snippet, not a rewrite.
#
# Usage:
#   ./scripts/setup/init.sh [--stack react-vite-feature|react-vite-fsd|react-next-app] [target-dir]
#   ./scripts/setup/init.sh --dry-run [target-dir]
#   ./scripts/setup/init.sh --verify [target-dir]

set -euo pipefail

SETUP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=scripts/setup/lib/common.sh
source "$SETUP_DIR/lib/common.sh"

PACK_DIR="$(compforge_pack_dir "$SETUP_DIR")"
TEMPLATES="$PACK_DIR/templates"
STACK=""
TARGET=""
DRY_RUN=0
VERIFY=0

AGENTS_BEGIN="<!-- BEGIN COMPFORGE (generated by compforge init; do not edit — re-run init) -->"
AGENTS_END="<!-- END COMPFORGE -->"
LOCK_NAME="compforge-lock.json"

# shellcheck source=scripts/setup/lib/init-core.sh
source "$SETUP_DIR/lib/init-core.sh"
# shellcheck source=scripts/setup/lib/init-delivery.sh
source "$SETUP_DIR/lib/init-delivery.sh"
# shellcheck source=scripts/setup/lib/init-selftest.sh
source "$SETUP_DIR/lib/init-selftest.sh"

usage() {
  cat <<USAGE
compforge init

Usage:
  init.sh [--stack react-vite-feature|react-vite-fsd|react-next-app] [--dry-run] [target-dir]
  init.sh --verify [target-dir]

target-dir defaults to the current directory. The stack is detected from
package.json and the src/ layout; pass --stack when detection reports ambiguity.

--verify re-reads $LOCK_NAME, confirms the delivered files are still there,
refuses a tsconfig without strict: true, and re-runs the negative self-test
so a dead guard cannot pass unnoticed.
USAGE
}

while [ "$#" -gt 0 ]; do
  case "$1" in
    --stack) STACK="${2:-}"; shift 2 ;;
    --dry-run) DRY_RUN=1; shift ;;
    --verify) VERIFY=1; shift ;;
    -h|--help) usage; exit 0 ;;
    -*) red "unknown flag: $1"; usage; exit 2 ;;
    *) TARGET="$1"; shift ;;
  esac
done

TARGET="$(cd "${TARGET:-.}" && pwd)"

if [ ! -f "$TARGET/package.json" ]; then
  red "no package.json in $TARGET — run init inside a project."
  exit 2
fi

# --- run ---------------------------------------------------------------------

if [ "$VERIFY" = 1 ]; then
  run_verify
  exit 0
fi

resolve_stack
require_strict_tsconfig

cyan "compforge init → $TARGET ($STACK)"

run_stack_init
install_agents_pointer
install_workflow
install_review_workflow
write_lock

if [ "${#MISSING_DEPS[@]}" -gt 0 ]; then
  yellow "missing devDependencies: ${MISSING_DEPS[*]}"
  yellow "install them, then re-run init to complete the self-test:"
  printf '\n  npm install -D %s\n\n' "${MISSING_DEPS[*]}"
  red "init incomplete: enforcement is not live until the self-test passes."
  exit 2
fi

if [ "$DRY_RUN" = 1 ]; then
  yellow "dry-run: skipping self-test."
  exit 0
fi

run_selftests
hint_tsc_if_missing

green "compforge init complete: constitution pointer + zones installed, blocking CI + non-blocking review workflow ready, self-test green."
