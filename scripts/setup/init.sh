#!/usr/bin/env bash
#
# compforge init — deliver Compforge's constitution and enforcement into a
# target project.
#
# Leaves two things behind that survive a clone:
#   1. An AGENTS.md pointer block — an agent that clones only the target repo
#      learns to read the pack before touching UI code. The Hard Rules are not
#      copied; the block records what this repo is pinned to.
#   2. The stack's enforcement template (ESLint import zones or steiger) plus a
#      GitHub Actions check, with per-feature zones generated from the
#      directories that actually exist.
#
# Then it runs a negative self-test: a deliberate violation must fail lint. A
# silent no-op (the .ts resolver trap) cannot survive an install.
#
# What it never does: overwrite a file it did not generate, install npm
# dependencies, or touch package.json. Existing files get a printed merge
# snippet instead; an existing AGENTS.md keeps everything outside the markers.
#
# Usage:
#   ./scripts/setup/init.sh [--stack react-vite-feature|react-vite-fsd|react-next-app] [target-dir]
#   ./scripts/setup/init.sh --dry-run [target-dir]
#   ./scripts/setup/init.sh --verify [target-dir]

set -euo pipefail

SETUP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=scripts/setup/lib/common.sh
source "$SETUP_DIR/lib/common.sh"

PACK_DIR="$(compforge_pack_dir "$SETUP_DIR")"
TEMPLATES="$PACK_DIR/templates"
STACK=""
TARGET=""
DRY_RUN=0
VERIFY=0

AGENTS_BEGIN="<!-- BEGIN COMPFORGE (generated by compforge init; do not edit — re-run init) -->"
AGENTS_END="<!-- END COMPFORGE -->"
LOCK_NAME="compforge-lock.json"

usage() {
  cat <<USAGE
compforge init

Usage:
  init.sh [--stack react-vite-feature|react-vite-fsd|react-next-app] [--dry-run] [target-dir]
  init.sh --verify [target-dir]

target-dir defaults to the current directory. The stack is detected from
package.json and the src/ layout; pass --stack when detection reports ambiguity.

--verify re-reads $LOCK_NAME, confirms the delivered files are still there, and
re-runs the negative self-test so a dead guard cannot pass unnoticed.
USAGE
}

while [ "$#" -gt 0 ]; do
  case "$1" in
    --stack) STACK="${2:-}"; shift 2 ;;
    --dry-run) DRY_RUN=1; shift ;;
    --verify) VERIFY=1; shift ;;
    -h|--help) usage; exit 0 ;;
    -*) red "unknown flag: $1"; usage; exit 2 ;;
    *) TARGET="$1"; shift ;;
  esac
done

TARGET="$(cd "${TARGET:-.}" && pwd)"

if [ ! -f "$TARGET/package.json" ]; then
  red "no package.json in $TARGET — run init inside a project."
  exit 2
fi

# --- pack identity ---------------------------------------------------------

pack_version() {
  python3 - "$PACK_DIR/.claude-plugin/plugin.json" <<'PY'
import json, sys
print(json.load(open(sys.argv[1])).get("version", "unknown"))
PY
}

pack_commit() {
  git -C "$PACK_DIR" rev-parse --short HEAD 2>/dev/null || printf 'unknown'
}

# --- stack detection -------------------------------------------------------
# Next is checked first and by dependency, not by folder: a Next App Router
# project also has src/features, so a layout-only check reported
# react-vite-feature and installed zones without the src/server boundary.

have_dep() {
  python3 - "$TARGET/package.json" "$1" <<'PY'
import json, sys
pkg = json.load(open(sys.argv[1]))
deps = {**pkg.get("dependencies", {}), **pkg.get("devDependencies", {})}
sys.exit(0 if sys.argv[2] in deps else 1)
PY
}

detect_stack() {
  local fsd=0 feature=0

  if have_dep next || compgen -G "$TARGET/next.config.*" >/dev/null 2>&1; then
    printf 'react-next-app'
    return
  fi

  for layer in entities widgets pages; do
    [ -d "$TARGET/src/$layer" ] && fsd=1
  done
  [ -d "$TARGET/src/features" ] && feature=1

  if [ "$fsd" = 1 ]; then
    printf 'react-vite-fsd'
  elif [ "$feature" = 1 ]; then
    printf 'react-vite-feature'
  else
    printf ''
  fi
}

resolve_stack() {
  if [ -n "$STACK" ]; then
    case "$STACK" in
      react-vite-feature|react-vite-fsd|react-next-app) return ;;
      *) red "unknown stack: $STACK"; exit 2 ;;
    esac
  fi

  STACK="$(detect_stack)"
  if [ -z "$STACK" ]; then
    red "cannot detect the stack from $TARGET (no next dependency, no features/, no FSD layers)."
    red "Pass --stack react-vite-feature | react-vite-fsd | react-next-app; do not guess."
    exit 2
  fi
  cyan "detected stack: $STACK"
}

# --- helpers ---------------------------------------------------------------

write_file() { # $1 = destination, stdin = content
  if [ "$DRY_RUN" = 1 ]; then
    yellow "dry-run: would write $1"
    cat >/dev/null
  else
    mkdir -p "$(dirname "$1")"
    cat >"$1"
    green "wrote $1"
  fi
}

MISSING_DEPS=()

require_dep() {
  if ! have_dep "$1"; then
    MISSING_DEPS+=("$1")
  fi
}

# Rewrite only the generated zone block, so hand edits outside it survive.
generate_zones() { # $1 = template, $2 = destination config
  python3 - "$1" "$2" "$TARGET" "$DRY_RUN" <<'PY'
import sys
from pathlib import Path

template, config, target, dry = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3]), sys.argv[4] == "1"
BEGIN = "// BEGIN COMPFORGE GENERATED FEATURE ZONES (do not edit; re-run compforge init)"
END = "// END COMPFORGE GENERATED FEATURE ZONES"

features_dir = target / "src" / "features"
features = sorted(
    p.name for p in features_dir.iterdir()
    if p.is_dir() and not p.name.startswith(("_", "."))
) if features_dir.is_dir() else []

indent = " " * 12
zones = []
for name in features:
    zones.append(
        f"{indent}{{\n"
        f"{indent}  target: './src/features/{name}',\n"
        f"{indent}  from: './src/features',\n"
        f"{indent}  except: ['./{name}'],\n"
        f"{indent}  message: 'No cross-feature imports; compose features at the app level.',\n"
        f"{indent}}},"
    )
block = "\n".join(zones)

source = config if config.exists() else template
text = source.read_text(encoding="utf-8")
if BEGIN not in text or END not in text:
    sys.stderr.write(f"marker block missing in {source}; not touching it.\n")
    sys.exit(3)

head, rest = text.split(BEGIN, 1)
_, tail = rest.split(END, 1)
body = head + BEGIN + ("\n" + block + "\n" + indent if block else "\n" + indent) + END + tail

if dry:
    print(f"dry-run: would write {config} with {len(features)} feature zone(s): {', '.join(features) or '(none)'}")
else:
    config.write_text(body, encoding="utf-8")
    print(f"wrote {config} with {len(features)} feature zone(s): {', '.join(features) or '(none)'}")
PY
}

install_eslint_entry() {
  if [ ! -f "$TARGET/eslint.config.js" ] && [ ! -f "$TARGET/eslint.config.mjs" ]; then
    write_file "$TARGET/eslint.config.js" <<'EOF'
import compforge from './eslint.compforge.config.js';

export default [...compforge];
EOF
  else
    yellow "eslint.config.js already exists — not touched. Merge with:"
    printf '\n  import compforge from '\''./eslint.compforge.config.js'\'';\n  // then spread ...compforge into your exported array\n\n'
  fi

  require_dep eslint
  require_dep eslint-plugin-import
  require_dep typescript-eslint

  CHECK_CMD="npx eslint --config eslint.compforge.config.js src"
}

# --- stacks ----------------------------------------------------------------

init_feature() {
  generate_zones "$TEMPLATES/react-vite-feature/eslint.compforge.config.js" "$TARGET/eslint.compforge.config.js"
  install_eslint_entry
}

init_next() {
  generate_zones "$TEMPLATES/react-next-app/eslint.compforge.config.js" "$TARGET/eslint.compforge.config.js"
  install_eslint_entry
}

init_fsd() {
  if [ -f "$TARGET/steiger.config.ts" ]; then
    yellow "steiger.config.ts already exists — not touched. Compare against:"
    yellow "  $TEMPLATES/react-vite-fsd/steiger.config.ts"
  else
    write_file "$TARGET/steiger.config.ts" <"$TEMPLATES/react-vite-fsd/steiger.config.ts"
  fi

  require_dep steiger
  require_dep '@feature-sliced/steiger-plugin'

  CHECK_CMD="npx steiger src"
}

run_stack_init() {
  case "$STACK" in
    react-vite-feature) init_feature ;;
    react-vite-fsd) init_fsd ;;
    react-next-app) init_next ;;
  esac
}

# --- constitution pointer ----------------------------------------------------
# The pointer is deliberately thin. Copying the Hard Rules into the target would
# go stale on every pack release — the drift this release exists to prevent.

install_agents_pointer() {
  python3 - "$TEMPLATES/agents/compforge-block.md" "$TARGET/AGENTS.md" "$STACK" "$CHECK_CMD" "$DRY_RUN" \
    "$AGENTS_BEGIN" "$AGENTS_END" <<'PY'
import sys
from pathlib import Path

template, agents, stack, check, dry = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3], sys.argv[4], sys.argv[5] == "1"
BEGIN, END = sys.argv[6], sys.argv[7]

block = (
    template.read_text(encoding="utf-8")
    .replace("__COMPFORGE_STACK__", stack)
    .replace("__COMPFORGE_CHECK_CMD__", check)
    .strip()
)

if not block.startswith(BEGIN) or not block.endswith(END):
    sys.exit(f"marker mismatch between {template} and init.sh; refusing to write {agents}.")

if agents.exists():
    text = agents.read_text(encoding="utf-8")
    if BEGIN in text and END in text:
        head, rest = text.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        body = head + block + tail
        action = ("update the Compforge block in", "updated the Compforge block in")
    else:
        body = text.rstrip() + "\n\n" + block + "\n"
        action = ("append the Compforge block to", "appended the Compforge block to")
else:
    body = "# Agent Instructions\n\n" + block + "\n"
    action = ("create", "created")

if dry:
    print(f"dry-run: would {action[0]} {agents}")
else:
    agents.write_text(body, encoding="utf-8")
    print(f"{action[1]} {agents}")
PY
}

write_lock() {
  local version commit
  version="$(pack_version)"
  commit="$(pack_commit)"

  if [ "$DRY_RUN" = 1 ]; then
    yellow "dry-run: would write $TARGET/$LOCK_NAME (compforge $version, stack $STACK)"
    return
  fi

  python3 - "$TARGET/$LOCK_NAME" "$version" "$commit" "$STACK" "$CHECK_CMD" <<'PY'
import json, sys, datetime
from pathlib import Path

lock, version, commit, stack, check = Path(sys.argv[1]), sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5]
lock.write_text(json.dumps({
    "compforge": {
        "version": version,
        "commit": commit,
        "source": "https://github.com/LooSung/compforge",
    },
    "installedAt": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
    "stack": stack,
    "checkCommand": check,
    "verifyCommand": "compforge init --verify",
}, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
print(f"wrote {lock}")
PY
}

install_workflow() {
  local wf="$TARGET/.github/workflows/compforge-check.yml"
  if [ -f "$wf" ]; then
    yellow "$wf already exists — not touched."
  else
    sed "s|__COMPFORGE_CHECK_CMD__|$CHECK_CMD|" "$TEMPLATES/github/compforge-check.yml" | write_file "$wf"
  fi
}

install_review_workflow() {
  local wf="$TARGET/.github/workflows/compforge-architecture-review.yml"
  if [ -f "$wf" ]; then
    yellow "$wf already exists — not touched."
  else
    write_file "$wf" <"$TEMPLATES/github/compforge-architecture-review.yml"
  fi
}

# --- self-tests ---------------------------------------------------------------
# The point: prove the delivered mechanism can fail. A violation must exit
# non-zero naming the rule, and a compliant file must pass — otherwise the
# enforcement is a silent no-op and init refuses to report success.

selftest_pointer() {
  python3 - "$TARGET/AGENTS.md" "$AGENTS_BEGIN" "$AGENTS_END" <<'PY'
import sys
from pathlib import Path

agents = Path(sys.argv[1])
BEGIN, END = sys.argv[2], sys.argv[3]

if not agents.exists():
    sys.exit(f"SELF-TEST FAILED: {agents} is missing; the constitution pointer was not delivered.")

text = agents.read_text(encoding="utf-8")
if BEGIN not in text or END not in text:
    sys.exit(f"SELF-TEST FAILED: no Compforge marker block in {agents}.")

block = text.split(BEGIN, 1)[1].split(END, 1)[0]
if "__COMPFORGE_" in block:
    sys.exit("SELF-TEST FAILED: an unsubstituted placeholder is left in the block; agents would read a template.")
for needed in ("$COMPFORGE_HOME", "skills/workflow/craft.md", "skills/principles/hard-rules.md"):
    if needed not in block:
        sys.exit(f"SELF-TEST FAILED: the block does not point at {needed}.")
PY
  green "self-test passed: AGENTS.md points at the pack and carries no placeholders."
}

# Build an eslint fixture with a deliberate violation and a compliant file.
# $1 = template, $2 = `cross-feature` to generate a per-feature zone (any other
# value relies on the template's own zones), $3 = fixture builder function.
selftest_eslint() {
  local template="$1" zone_kind="$2" build="$3"
  local st="$TARGET/.compforge-selftest"
  rm -rf "$st"
  "$build" "$st"

  python3 - "$template" "$st/eslint.selftest.config.js" "$zone_kind" <<'PY'
import sys
from pathlib import Path
template, out, kind = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
BEGIN = "// BEGIN COMPFORGE GENERATED FEATURE ZONES (do not edit; re-run compforge init)"
END = "// END COMPFORGE GENERATED FEATURE ZONES"
indent = " " * 12
zone = (
    f"{indent}{{\n"
    f"{indent}  target: './src/features/cf_a',\n"
    f"{indent}  from: './src/features',\n"
    f"{indent}  except: ['./cf_a'],\n"
    f"{indent}}},"
) if kind == "cross-feature" else ""
text = template.read_text(encoding="utf-8")
head, rest = text.split(BEGIN, 1)
_, tail = rest.split(END, 1)
out.write_text(head + BEGIN + "\n" + (zone + "\n" if zone else "") + indent + END + tail, encoding="utf-8")
PY

  local out rc=0
  out="$(cd "$st" && npx eslint --no-config-lookup --config eslint.selftest.config.js src 2>&1)" || rc=$?
  if [ "$rc" -eq 0 ] || ! printf '%s' "$out" | grep -q 'no-restricted-paths'; then
    red "SELF-TEST FAILED: a deliberate violation did not trip the zone rule."
    red "The enforcement would be a silent no-op. Raw output:"
    printf '%s\n' "$out"
    rm -rf "$st"
    exit 3
  fi

  rc=0
  out="$(cd "$st" && npx eslint --no-config-lookup --config eslint.selftest.config.js src/shared 2>&1)" || rc=$?
  if [ "$rc" -ne 0 ]; then
    red "SELF-TEST FAILED: a compliant file did not pass (config error, not a violation):"
    printf '%s\n' "$out"
    rm -rf "$st"
    exit 3
  fi

  rm -rf "$st"
}

fixture_cross_feature() { # $1 = fixture root
  mkdir -p "$1/src/features/cf_a" "$1/src/features/cf_b" "$1/src/shared"
  printf 'export const util = 1;\n' >"$1/src/features/cf_b/util.ts"
  printf "import { util } from '../cf_b/util';\nexport const a = util;\n" >"$1/src/features/cf_a/index.ts"
  printf 'export const ok = 2;\n' >"$1/src/shared/ok.ts"
}

fixture_server_leak() { # $1 = fixture root
  mkdir -p "$1/src/features/cf_a" "$1/src/server" "$1/src/shared"
  printf 'export const secret = 1;\n' >"$1/src/server/secret.ts"
  printf "import { secret } from '../../server/secret';\nexport const a = secret;\n" >"$1/src/features/cf_a/index.ts"
  printf 'export const ok = 2;\n' >"$1/src/shared/ok.ts"
}

selftest_feature() {
  selftest_eslint "$TEMPLATES/react-vite-feature/eslint.compforge.config.js" cross-feature fixture_cross_feature
  green "self-test passed: a cross-feature import fails, a compliant file passes."
}

selftest_next() {
  local tpl="$TEMPLATES/react-next-app/eslint.compforge.config.js"
  selftest_eslint "$tpl" cross-feature fixture_cross_feature
  # The boundary that only exists on this stack: a client feature reaching into
  # server-only code. Detecting the stack as react-vite-feature silently drops it.
  selftest_eslint "$tpl" server fixture_server_leak
  green "self-test passed: cross-feature and server-only imports both fail, compliant files pass."
}

selftest_fsd() {
  local st="$TARGET/.compforge-selftest"
  rm -rf "$st"
  mkdir -p "$st/src/features/cf-a/ui" "$st/src/features/cf-b/ui"
  printf 'export const B = 1;\n' >"$st/src/features/cf-b/ui/b.ts"
  printf 'export { B } from "../../cf-b/ui/b";\n' >"$st/src/features/cf-a/ui/a.ts"
  printf 'export {};\n' >"$st/src/features/cf-a/index.ts"
  printf 'export {};\n' >"$st/src/features/cf-b/index.ts"
  cp "$TEMPLATES/react-vite-fsd/steiger.config.ts" "$st/steiger.config.ts"

  local out rc=0
  out="$(cd "$st" && npx steiger src 2>&1)" || rc=$?
  if [ "$rc" -eq 0 ] || ! printf '%s' "$out" | grep -q 'forbidden-imports'; then
    red "SELF-TEST FAILED: a deliberate cross-feature import did not trip fsd/forbidden-imports."
    red "The enforcement would be a silent no-op (or steiger crashed). Raw output:"
    printf '%s\n' "$out"
    rm -rf "$st"
    exit 3
  fi

  rm -rf "$st"
  green "self-test passed: steiger fails on a cross-feature import."
}

run_selftests() {
  selftest_pointer
  case "$STACK" in
    react-vite-feature) selftest_feature ;;
    react-vite-fsd) selftest_fsd ;;
    react-next-app) selftest_next ;;
  esac
}

# --- verify ------------------------------------------------------------------
# Answers one question: is the guard this repo claims to have still alive?

run_verify() {
  local lock="$TARGET/$LOCK_NAME"
  cyan "compforge verify → $TARGET"

  if [ ! -f "$lock" ]; then
    red "no $LOCK_NAME in $TARGET — run compforge init first."
    exit 2
  fi

  STACK="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["stack"])' "$lock")"
  CHECK_CMD="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["checkCommand"])' "$lock")"
  local locked_version detected
  locked_version="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["compforge"]["version"])' "$lock")"

  cyan "locked: compforge $locked_version, stack $STACK"

  detected="$(detect_stack)"
  if [ -n "$detected" ] && [ "$detected" != "$STACK" ]; then
    red "DRIFT: the project now looks like '$detected' but the lock says '$STACK'."
    red "Re-run compforge init so the delivered zones match the project."
    exit 3
  fi

  local installed
  installed="$(pack_version)"
  if [ "$installed" != "$locked_version" ]; then
    yellow "pack version drift: installed $installed, locked $locked_version. Re-run init to re-pin."
  fi

  run_selftests
  green "compforge verify complete: pointer intact, guard still fails on a violation."
}

# --- run ---------------------------------------------------------------------

if [ "$VERIFY" = 1 ]; then
  run_verify
  exit 0
fi

resolve_stack

cyan "compforge init → $TARGET ($STACK)"

run_stack_init
install_agents_pointer
install_workflow
install_review_workflow
write_lock

if [ "${#MISSING_DEPS[@]}" -gt 0 ]; then
  yellow "missing devDependencies: ${MISSING_DEPS[*]}"
  yellow "install them, then re-run init to complete the self-test:"
  printf '\n  npm install -D %s\n\n' "${MISSING_DEPS[*]}"
  red "init incomplete: enforcement is not live until the self-test passes."
  exit 2
fi

if [ "$DRY_RUN" = 1 ]; then
  yellow "dry-run: skipping self-test."
  exit 0
fi

run_selftests

green "compforge init complete: constitution pointer + zones installed, blocking CI + non-blocking review workflow ready, self-test green."
